from __future__ import annotations

from tkinter import ttk


def configure_styles(widget) -> None:
    """为整个应用配置 ttk 主题与自定义样式。"""
    style = ttk.Style(widget)
    style.theme_use("clam")
    font = ("Microsoft YaHei UI", 10)
    widget.option_add("*Font", font)
    style.configure("App.TFrame", background="#F4F7FB")
    style.configure("TFrame", background="#FFFFFF")
    style.configure("Card.TFrame", background="#FFFFFF", relief="solid", borderwidth=1)
    style.configure("Popup.TFrame", background="#FFFFFF")
    style.configure("TLabel", background="#FFFFFF", foreground="#334155", font=font)
    style.configure("Title.TLabel", background="#F4F7FB", foreground="#0F172A", font=("Microsoft YaHei UI", 20, "bold"))
    style.configure("Subtitle.TLabel", background="#F4F7FB", foreground="#64748B", font=("Microsoft YaHei UI", 10))
    style.configure("Section.TLabel", background="#FFFFFF", foreground="#0F172A", font=("Microsoft YaHei UI", 10, "bold"))
    style.configure("PopupTitle.TLabel", background="#FFFFFF", foreground="#0F172A", font=("Microsoft YaHei UI", 10, "bold"))
    style.configure("Card.TLabelframe", background="#FFFFFF", relief="solid", borderwidth=1)
    style.configure("Card.TLabelframe.Label", background="#FFFFFF", foreground="#0F172A", font=("Microsoft YaHei UI", 11, "bold"))
    style.configure("TLabelframe", background="#FFFFFF")
    style.configure("TLabelframe.Label", background="#FFFFFF", foreground="#0F172A", font=("Microsoft YaHei UI", 10, "bold"))
    style.configure("TNotebook", background="#F4F7FB", borderwidth=0)
    style.configure("TNotebook.Tab", padding=(14, 9), background="#E8EEF7", foreground="#475569")
    style.map("TNotebook.Tab", background=[("selected", "#FFFFFF")], foreground=[("selected", "#1D4ED8")])
    style.configure("TButton", padding=(10, 6), background="#E8EEF7", foreground="#334155", borderwidth=0)
    style.map("TButton", background=[("active", "#DCE5F2"), ("disabled", "#E2E8F0")])
    style.configure("Primary.TButton", background="#2563EB", foreground="#FFFFFF", font=("Microsoft YaHei UI", 10, "bold"))
    style.map("Primary.TButton", background=[("active", "#1D4ED8"), ("pressed", "#1E40AF")])
    style.configure("Success.TButton", background="#0F766E", foreground="#FFFFFF", font=("Microsoft YaHei UI", 10, "bold"))
    style.map("Success.TButton", background=[("active", "#0D9488"), ("disabled", "#CBD5E1")])
    style.configure("Link.TButton", background="#FFFFFF", foreground="#2563EB", padding=(6, 3))
    style.configure("Picker.TButton", background="#FFFFFF", foreground="#334155", anchor="w", relief="solid", borderwidth=1, padding=(8, 6))
    style.map("Picker.TButton", background=[("active", "#F8FAFC")])
    style.configure("TEntry", fieldbackground="#FFFFFF", bordercolor="#CBD5E1", lightcolor="#CBD5E1", darkcolor="#CBD5E1", padding=5)
    style.configure("TCombobox", fieldbackground="#FFFFFF", bordercolor="#CBD5E1", arrowsize=14, padding=4)
    style.configure("Treeview", background="#FFFFFF", fieldbackground="#FFFFFF", foreground="#334155", rowheight=30, borderwidth=0)
    style.configure("Treeview.Heading", background="#EEF2F7", foreground="#334155", font=("Microsoft YaHei UI", 10, "bold"), padding=(8, 7), relief="flat")
    style.map("Treeview", background=[("selected", "#DBEAFE")], foreground=[("selected", "#1E3A8A")])
    style.configure("Status.TFrame", background="#EAF2FF")
    style.configure("Status.TLabel", background="#EAF2FF", foreground="#334155")
    style.configure("StatusDot.TLabel", background="#EAF2FF", foreground="#2563EB")
